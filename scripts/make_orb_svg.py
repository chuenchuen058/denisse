"""Write assets/orb.svg -- the tray orb, pulsing, for the README.

The orb itself is drawn with PIL frame by frame (floating_orb.py). GitHub
can't run that, but it does play SVG animations inside a README image, so
this redraws the same orb as vectors from the same constants:

  core   radial gradient ACCENT_BRIGHT -> ACCENT_DEEP, with the offset
         highlight clipped to the sphere, radius breathing 0.8152 -> 1.0
  glow   ACCENT disc at 0.6 x the orb's diameter, blurred, alpha 150 -> 229
  ring   two arcs (150 deg bright, 60 deg violet), one turn every 6 s

One breath is BREATH_FRAMES * TICK_MS (1.2 s) on _breath_curve's sine, so
re-run this after changing any of those and the README stays in step:

    .venv\\Scripts\\python.exe scripts\\make_orb_svg.py
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import floating_orb as fo  # noqa: E402  (after sys.path is set)

OUT = os.path.join(ROOT, "assets", "orb.svg")
DISPLAY_PX = 160  # the widget is 58 px across; this is how big the README shows it


def hexc(rgb):
    return "#%02x%02x%02x" % tuple(rgb)


def main():
    orb = fo.ORB_SIZE
    total = orb + fo.GLOW_PAD * 2
    c = total / 2
    r = orb / 2
    ring_r = r + fo.RING_GAP
    rest = 0.8152  # _make_orb_core: r = px/2 * (0.8152 + 0.1848 * breath)
    breath_s = fo.BREATH_FRAMES * fo.TICK_MS / 1000
    ring_s = fo.RING_FRAMES * fo.TICK_MS / 1000
    blur = total * 0.05  # GaussianBlur(size * 0.05) at supersample, in final px
    circ = 2 * math.pi * ring_r
    # _breath_curve is a sine from 0 up to 1 and back: ease-in-out both halves
    sine = 'calcMode="spline" keyTimes="0;0.5;1" keySplines="0.37 0 0.63 1;0.37 0 0.63 1"'

    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{DISPLAY_PX}" height="{DISPLAY_PX}" viewBox="0 0 {total} {total}" role="img" aria-label="Denisse's orb, breathing">
  <!-- generated by scripts/make_orb_svg.py from floating_orb.py; edit there, not here -->
  <defs>
    <radialGradient id="core" cx="0" cy="0" r="{r}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{hexc(fo.ACCENT_BRIGHT)}"/>
      <stop offset="1" stop-color="{hexc(fo.ACCENT_DEEP)}"/>
    </radialGradient>
    <filter id="glow" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="{blur:.2f}"/></filter>
    <filter id="soft" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="{orb * 0.05:.2f}"/></filter>
    <clipPath id="sphere"><circle r="{r}"/></clipPath>
  </defs>
  <g transform="translate({c} {c})">
    <circle r="{orb * 0.6:.2f}" fill="{hexc(fo.ACCENT)}" filter="url(#glow)" opacity="{150 / 255:.3f}">
      <animate attributeName="opacity" values="{150 / 255:.3f};{229.2 / 255:.3f};{150 / 255:.3f}" dur="{breath_s}s" repeatCount="indefinite" {sine}/>
    </circle>
    <g>
      <animateTransform attributeName="transform" type="scale" values="{rest};1;{rest}" dur="{breath_s}s" repeatCount="indefinite" {sine}/>
      <circle r="{r}" fill="url(#core)"/>
      <g clip-path="url(#sphere)">
        <circle cx="{-0.62 * r:.2f}" cy="{-0.68 * r:.2f}" r="{0.42 * r:.2f}" fill="#ffffff" opacity="{130 / 255:.3f}" filter="url(#soft)"/>
      </g>
    </g>
    <g fill="none" stroke-width="3.5">
      <animateTransform attributeName="transform" type="rotate" from="0" to="360" dur="{ring_s}s" repeatCount="indefinite"/>
      <circle r="{ring_r}" stroke="{hexc(fo.ACCENT_BRIGHT)}" stroke-dasharray="{circ * 150 / 360:.2f} {circ:.2f}"/>
      <circle r="{ring_r}" stroke="#7c3aed" stroke-dasharray="{circ * 60 / 360:.2f} {circ:.2f}" stroke-dashoffset="{-circ / 2:.2f}"/>
    </g>
  </g>
</svg>
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(svg)
    print(f"wrote {OUT}: {breath_s}s breath, {ring_s}s ring turn, shown at {DISPLAY_PX}px")


if __name__ == "__main__":
    main()
