"""Generate the STATE NOW block from the runner's own files (queue, parked,
archive, state.json) so a new chat starts from live state, not from memory.

    .venv\\Scripts\\python.exe orchestra\\state_now.py          # print + write
Writes .review/STATE_NOW.md, and also "<vault>/STATE NOW.md" when the
DENISSE_VAULT environment variable (else config.json vault_dir) points at the
Obsidian vault.

Only facts the files prove go in. Calendar / mail sources can be added later as
extra sections, each read live from its real app, never copied by hand.
"""
from __future__ import annotations

import datetime as dt
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import runner as R  # noqa: E402


def _vault() -> str:
    """DENISSE_VAULT, else config.json vault_dir (the runner's own copy); '' when neither."""
    found = os.environ.get("DENISSE_VAULT") or R.C.get("vault_dir") or ""
    return os.path.expandvars(os.path.expanduser(found)) if found else ""


HEADER = ("---\nname: STATE NOW\ndescription: Generated by Orchestra's state_now.py after every tick. "
          "Do not edit by hand.\nupdated: {date}\n---\n\n")


def _title(p: Path) -> str:
    try:
        return R.parse_task(p).title
    except Exception:
        return p.stem


def build() -> str:
    state = R.load_state()
    now = R.now()
    out = [f"## STATE NOW", f"_generated {now.isoformat(sep=' ', timespec='minutes')} by orchestra/state_now.py — do not edit by hand_", ""]

    try:
        line = R.campaign.campaign_line(R.REVIEW)
    except Exception as e:  # a bad campaign file must not take STATE NOW down with it
        line = f"**Sprint:** (campaign line failed: {e})"
    if line:
        out += [line, ""]

    running = "nothing"
    if R.LOCK_FILE.exists():
        try:
            lk = json.loads(R.LOCK_FILE.read_text(encoding="utf-8"))
            running = f"{lk.get('task', '(starting)')} since {lk.get('since', '?')}"
        except json.JSONDecodeError:
            running = "(lock file unreadable)"
    out += ["**Running:** " + running, ""]

    limited = []
    for lane in sorted(state.get("lanes", {})):
        until = R.lane_limited(state, lane)
        if until:
            fb = (R.C.get("lane_fallback", {"codex": "claude"}) or {}).get(lane)
            limited.append(f"{lane} until {until.isoformat(sep=' ', timespec='minutes')}"
                           + (f" (tasks fall back to {fb} unless Lane-Fixed)" if fb else ""))
    out += ["**Limited lanes:** " + ("; ".join(limited) or "none"), ""]

    try:
        import power
        out += ["**Power:** " + power.describe(power.power_status(), R.C), ""]
    except Exception as e:  # a power reading must never break STATE NOW
        out += [f"**Power:** unknown ({e})", ""]

    waiting = []
    for why in sorted(R.PARKED.glob("*.why.txt")) if R.PARKED.exists() else []:
        slug = why.name[: -len(".why.txt")]
        reason = why.read_text(encoding="utf-8").strip().split(" ", 1)[-1]
        waiting.append(f"- {_title(R.PARKED / (slug + '.md'))} — {reason}")
    try:
        R.drop_landed(state)  # a branch since merged (or gone) leaves the list
    except Exception as e:  # git trouble must not take STATE NOW down; list them as before
        waiting.append(f"- (could not check which branches have landed: {e})")
    for slug, ts in state.get("tasks", {}).items():
        m = ts.get("merge", "")
        if R.merge_waiting(m):
            waiting.append(f"- merge `review/{slug}` — {m}")
    for slug, ts in state.get("tasks", {}).items():
        last = (ts.get("history") or [{}])[-1]
        if last.get("denied"):
            waiting.append(f"- `{slug}`: session was refused {', '.join(sorted(set(last['denied'])))}"
                           " — widen the lane's allow list if that was needed (orchestra/runner.py, or .review/lanes.json)")
        if last.get("main_checkout_changed"):
            waiting.append(f"- `{slug}`: the main checkout changed during its run: "
                           f"{', '.join(last['main_checkout_changed'])} — a session writing outside its worktree, or you editing")
        if last.get("hooks_loaded") is False:
            waiting.append(f"- `{slug}`: the guard hook never fired in its run — check `claude --settings` still loads hooks")
        if str(last.get("premise", "")).lower().startswith("wrong"):
            waiting.append(f"- `{slug}`: report says the task's premise was {last['premise']}")
    out += ["**Waiting on Chuen:**"] + (waiting or ["- nothing"]) + [""]

    queue = R.load_queue() if R.QUEUE.exists() else []
    out.append(f"**Open queue:** {len(queue)} task(s)")
    for t in queue[:10]:
        ts = state.get("tasks", {}).get(t.slug, {})
        why = R.why_not_runnable(t, state) or "runnable"
        out.append(f"- [{t.priority}/{t.kind}] {t.title} — attempts {ts.get('attempts', 0)}, {why}")
    out.append("")

    closed = []
    for day in (now.date(), now.date() - dt.timedelta(days=1)):
        d = R.ARCHIVE / day.isoformat()
        if d.exists():
            closed += [f"- {day.isoformat()}: {_title(p)}" for p in sorted(d.glob("*.md"))
                       if not p.name.endswith(".report.md") and _is_task(p)]
    out += ["**Closed (today + yesterday):**"] + (closed or ["- nothing"]) + [""]

    u = R.today_usage(state)
    total = u["work_s"] + u["maint_s"]
    share = f"{100 * u['maint_s'] / total:.0f}%" if total else "n/a"
    out.append(f"**Today's runtime:** {u['work_s'] // 60} min his work, {u['maint_s'] // 60} min "
               f"maintenance (maintenance share {share}, cap {int(R.C['maint_share'] * 100)}%)")
    est = f", {u['estimated_runs']} run(s) estimated because they were killed before reporting" if u["estimated_runs"] else ""
    out.append(f"**Spend today:** ${u['cost_usd']:.2f} of the ${R.C['daily_spend_cap_usd']:.2f} cap{est}. "
               "From claude's own cost figures; check the real balance in the dashboards now and then.")
    return "\n".join(out) + "\n"


def _is_task(p: Path) -> bool:
    try:
        return p.read_text(encoding="utf-8").lstrip().startswith("# ")
    except OSError:
        return False


def write() -> str:
    text = build()
    R.REVIEW.mkdir(parents=True, exist_ok=True)
    (R.REVIEW / "STATE_NOW.md").write_text(text, encoding="utf-8")
    vault = _vault()
    if not os.environ.get("ORCHESTRA_REPO") and vault and Path(vault).is_dir():  # tests never touch the real vault
        (Path(vault) / "STATE NOW.md").write_text(HEADER.format(date=R.now().date().isoformat()) + text,
                                                  encoding="utf-8")
    return text


if __name__ == "__main__":
    print(write())
